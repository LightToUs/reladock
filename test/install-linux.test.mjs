import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';

test('agent installer and apply service require the fixed conntrack executable',async()=>{
 const installer=await readFile(join(process.cwd(),'deploy','install-linux.sh'),'utf8');
 assert.match(installer,/\/usr\/sbin\/conntrack/);
 assert.match(installer,/conntrack-tools|apt-get install -y conntrack/);
 assert.match(installer,/Unable to install conntrack tools/);
 const apply=await readFile(join(process.cwd(),'deploy','reladock-agent-apply.service'),'utf8');
 assert.match(apply,/^ExecStartPre=\/usr\/sbin\/conntrack --version$/m);
 assert.match(apply,/^CapabilityBoundingSet=CAP_NET_ADMIN$/m);
 assert.match(apply,/^Requires=reladock-agent-network\.service$/m);
 assert.match(apply,/^After=.*reladock-agent-network\.service$/m);
 assert.match(installer,/test -f "\$release\/reladock-agent-network\.service"/);
 assert.match(installer,/install .*reladock-agent-network\.service.*\/etc\/systemd\/system\/reladock-agent-network\.service/);
 const network=await readFile(join(process.cwd(),'deploy','reladock-agent-network.service'),'utf8');
 assert.match(network,/^ConditionPathExists=\/etc\/reladock\/network-managed$/m);
 assert.match(network,/^User=root$/m);
 assert.match(network,/^Type=oneshot$/m);
 assert.match(network,/^ExecStart=\/opt\/reladock\/reladock-agent prepare-network .*--node \$\{RELADOCK_NODE\} .*--snat \$\{RELADOCK_SNAT\} .*--shaping-interface \$\{RELADOCK_SHAPING_INTERFACE\}/m);
 assert.doesNotMatch(network,/^ExecStart=\/usr\/sbin\/(?:sysctl|ethtool|ip) /m);
 assert.match(network,/^CapabilityBoundingSet=CAP_NET_ADMIN$/m);
 assert.match(network,/^ProtectSystem=strict$/m);
 const validation=await readFile(join(process.cwd(),'deploy','reladock-agent.service'),'utf8');
 assert.doesNotMatch(validation,/^ExecStartPre=.*conntrack/m);
 assert.match(validation,/^CapabilityBoundingSet=$/m);
 assert.doesNotMatch(validation,/^AmbientCapabilities=CAP_NET_ADMIN$/m);
 assert.doesNotMatch(installer,/systemctl enable --now reladock-agent-apply/);
 const bootstrap=await readFile(join(process.cwd(),'deploy','bootstrap-agent.sh'),'utf8');
 assert.match(bootstrap,/1\) Enable forwarding \(apply mode\)/);
 assert.match(bootstrap,/2\) Keep validation-only \(default\)/);
 assert.match(bootstrap,/Type ENABLE to confirm:/);
 assert.match(bootstrap,/reladock-agent preflight-apply/);
 assert.match(bootstrap,/systemctl enable --now reladock-agent-network\.service/);
 assert.match(bootstrap,/systemctl disable --now reladock-agent\.service/);
 assert.match(bootstrap,/systemctl enable --now reladock-agent-apply\.service/);
 assert.match(bootstrap,/\/etc\/reladock\/network-managed/);
 assert.match(bootstrap,/install -o reladock -g reladock -m 0600 "\$temp\/shaping\.json" \/etc\/reladock\/shaping\.json/);
 assert.match(bootstrap,/apply_authoritative_listen=.*listen-address/);
 assert.match(bootstrap,/\[ "\$apply_snat" = "\$apply_authoritative_listen" \]/);
 for(const path of ['/etc/reladock/shaping.json','/etc/reladock/network-managed','/etc/systemd/system/reladock-agent-network.service'])assert.match(bootstrap,new RegExp(path.replaceAll('/','\\/')));
 assert.match(bootstrap,/apply_preparation_active=1/);
 assert.match(bootstrap,/apply_preserve_temp=1/);
 assert.match(bootstrap,/\[ "\$apply_result" -eq 2 \] \|\| \[ "\$apply_result" -eq 3 \]/);
});
